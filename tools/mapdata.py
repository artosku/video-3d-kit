"""Bakes the public map data (data/maps/*.json, Natural Earth land 110m + Indonesian provinces) into web/maps.js (compact rings) for the uang scenes.
    python tools/mapdata.py"""
import json, os
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
def rings(geom, nd):
    polys = geom['coordinates'] if geom['type'] == 'MultiPolygon' else [geom['coordinates']]
    return [[[round(x, nd), round(y, nd)] for x, y in p[0]] for p in polys]
land = json.load(open(os.path.join(root, 'data/maps/land110.json'), encoding='utf-8'))
world = []
for f in land['features']:
    for r in rings(f['geometry'], 1):
        if min(y for x, y in r) > -60: world.append(r)
prov = json.load(open(os.path.join(root, 'data/maps/idprov.json'), encoding='utf-8'))
ID = [{'n': f['properties']['Propinsi'], 'r': rings(f['geometry'], 2)} for f in prov['features']]
open(os.path.join(root, 'web/maps.js'), 'w', encoding='utf-8').write('// generated by tools/mapdata.py (public Natural Earth + BAKOSURTANAL province data)\nexport const WORLD = ' + json.dumps(world, separators=(',', ':')) + ';\nexport const ID_PROV = ' + json.dumps(ID, separators=(',', ':')) + ';\n')
print('web/maps.js', len(world), 'world rings,', len(ID), 'provinces')
